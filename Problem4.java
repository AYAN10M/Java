import java.util.*;

class Solution {
    public static void main(String args[]) {
        Scanner sc = new Scanner(System.in);

        int n1 = sc.nextInt();
        sc.nextLine();
        double d1 = sc.nextDouble();
        sc.nextLine();
        String s1 = sc.nextLine();

        System.out.println("String: " + s1);
        System.out.println("Double: " + d1);
        System.out.println("Int: " + n1);

        sc.close();
    }
}

